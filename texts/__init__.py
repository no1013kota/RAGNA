"""Discordに表示される日本語の文言を、まとめて置いておく場所。

このパッケージのファイルを書き換えるだけで、Botの表示文を変更できます。
Pythonの知識がなくても編集できるよう、次のルールで作っています。

==================================================
どこに何が書いてあるか
==================================================
- ``panels.py``         … 常設パネルの表題（チャンネルに置きっぱなしのパネル）
- ``channels.py``       … Botが自動で作るチャンネル・カテゴリーの名前
- ``common.py``         … どの機能でも使う共通の案内文・エラー文
- ``familiar.py``       … 使い魔（ガチャ・使い魔管理・一覧・合成・売却）
- ``guild.py``          … ギルド（設立・参加・脱退・管理・ギルド情報）
- ``battle.py``         … ギルドバトル（申請・募集・出場登録・清算）
- ``battle_display.py`` … バトル中の表示（戦況・行動ログ・結果）
- ``coin.py``           … coinとATM
- ``member.py``         … メンバー登録・招待pt・仮メンバー評価・クラスチェンジ
- ``hotel.py``          … 宿屋
- ``ticket.py``         … お問い合わせ窓口

==================================================
編集するときのルール
==================================================
1. ``=`` の右側にある「"」で囲まれた部分が、実際に表示される文章です。
   「"」の内側だけを書き換えてください。「"」そのものは消さないでください。

2. ``{name}`` のような波かっこは、Botが値を入れ替える場所です。
   例）``"{name} を{count}体売却しました。"`` → 「ゴブリン を3体売却しました。」
   波かっこの中の英単語は変えないでください。消したり増やしたりもしないでください。
   文章の中での位置は自由に動かせます。

3. 「"」を3つ並べた記号で囲まれた文章は、改行をそのまま表示します。
   行を増やしても構いません。

4. 行頭の ``#`` で始まる行は説明用のメモで、表示はされません。

5. ``-# `` で始まる行はDiscordで小さな文字になります。

6. 書き換えたら、次のコマンドで壊れていないか確認できます。
     .venv/bin/python scripts/check_project.py

==================================================
ここに置かないもの
==================================================
- 使い魔やスキルの名前・説明文 … ``data/master/*.json`` にあります
- 金額・確率・上限などの数値   … ``data/master/balance.json`` にあります
- チャンネルIDやロールID       … Railwayの環境変数と ``config.py`` にあります
- 開発者向けのログ・例外文     … 利用者には見えないため、各Pythonファイルのまま
"""
